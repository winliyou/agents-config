#!/usr/bin/env node
/**
 * 生成 Figma 本地开发插件：把设计规格（spec.json）与插件运行时打包成
 * code.js，供 Figma 桌面端「导入插件」直接运行。
 *
 * 支持参数（便于跨项目复用）：
 *   node build-figma-plugin.mjs [--spec <path>] [--out <dir>] [--name <pluginName>]
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const SCRIPTS_DIR = dirname(fileURLToPath(import.meta.url));

// 解析 CLI 参数
const args = process.argv.slice(2);
function getArg(flag, fallback) {
  const idx = args.indexOf(flag);
  return idx !== -1 && args[idx + 1] ? args[idx + 1] : fallback;
}

const SPEC = getArg('--spec', join(process.cwd(), 'spec.json'));
const RUNTIME = getArg('--runtime', join(SCRIPTS_DIR, 'figma-runtime.js'));
const OUT = getArg('--out', join(process.cwd(), 'figma-plugin'));
const PLUGIN_NAME = getArg('--name', 'Design Kit');
const PLUGIN_ID = getArg('--id', 'universal-design-kit');

let commit = 'dev';
try { commit = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch (e) {}

let spec;
if (existsSync(SPEC)) {
  spec = JSON.parse(readFileSync(SPEC, 'utf8'));
} else if (existsSync(join(OUT, 'code.js'))) {
  const existingCode = readFileSync(join(OUT, 'code.js'), 'utf8');
  const startIdx = existingCode.indexOf('var SPEC = ');
  const endIdx = existingCode.indexOf(';\n', startIdx);
  if (startIdx >= 0 && endIdx > startIdx) {
    const jsonStr = existingCode.slice(startIdx + 'var SPEC = '.length, endIdx).trim();
    spec = JSON.parse(jsonStr);
  } else {
    throw new Error('Cannot locate existing SPEC in code.js');
  }
} else {
  throw new Error(`Neither spec.json (${SPEC}) nor code.js exists to build plugin`);
}
const runtime = readFileSync(RUNTIME, 'utf8');

spec.meta = spec.meta || {};
spec.meta.builtAt = new Date().toISOString();
spec.meta.commit = commit;

const code = `// ${PLUGIN_NAME} — generated by build-figma-plugin.mjs\n` +
  '// 数据来源：spec.json（由 tokens / UI 提取脚本生成）\n' +
  'var SPEC = ' + JSON.stringify(spec) + ';\n' + runtime;

const manifest = {
  name: PLUGIN_NAME,
  id: PLUGIN_ID,
  api: '1.0.0',
  main: 'code.js',
  editorType: ['figma'],
  networkAccess: { allowedDomains: ['none'] }
};

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(join(OUT, 'code.js'), code);
console.log('plugin written:', OUT);
console.log('code.js bytes', code.length, 'screens', spec.meta.screenCount || (spec.screens ? spec.screens.length : 0), 'variables', spec.variables ? spec.variables.length : 0);
